// ── SEARCH HELPER ────────────────────────────────────────────────────────
export function searchProducts(
  query: string,
  _searchType: string
): { results: SearchResult[]; total_results: number; execution_time_ms: number } {
  if (!query.trim()) return { results: [], total_results: 0, execution_time_ms: 0 }

  const q = query.toLowerCase()
  const matched = MOCK_PRODUCTS.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.sku.toLowerCase().includes(q) ||
      (p.description ?? '').toLowerCase().includes(q) ||
      (p.category ?? '').toLowerCase().includes(q) ||
      (p.brand ?? '').toLowerCase().includes(q) ||
      Object.values(p.attributes).some((v) => String(v).toLowerCase().includes(q)) ||
      Object.values(p.specifications).some((v) => String(v).toLowerCase().includes(q))
  )

  const results: SearchResult[] = matched.map((p, i) => {
    const nameMatch = p.name.toLowerCase().includes(q)
    const skuMatch = p.sku.toLowerCase().includes(q)
    const descMatch = (p.description ?? '').toLowerCase().includes(q)
    const catMatch = (p.category ?? '').toLowerCase().includes(q)

    let matched_field = 'attributes'
    if (nameMatch) matched_field = 'name'
    else if (skuMatch) matched_field = 'sku'
    else if (descMatch) matched_field = 'description'
    else if (catMatch) matched_field = 'category'

    return {
      product_id: p.id,
      sku: p.sku,
      name: p.name,
      category: p.category,
      description: p.description,
      score: Math.max(0.65, 0.98 - i * 0.035),
      matched_field,
      explanation: `Matched via ${matched_field} — "${q}" found in product ${matched_field}`,
      attributes: p.attributes,
    }
  })

  return {
    results: results.slice(0, 20),
    total_results: results.length,
    execution_time_ms: Math.floor(Math.random() * 80) + 12,
  }
}
